-- Jalankan seluruh SQL ini di Supabase > SQL Editor.
-- Mengaktifkan RLS dan membuat tabel inti MDA Universe.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique check (char_length(username) between 2 and 24),
  bio text default '' check (char_length(bio) <= 160),
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create table if not exists public.friendships (
  id bigint generated by default as identity primary key,
  requester uuid not null references public.profiles(id) on delete cascade,
  addressee uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending' check (status in ('pending','accepted')),
  created_at timestamptz default now(),
  unique(requester, addressee),
  check (requester <> addressee)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  receiver_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz default now()
);

alter table public.profiles enable row level security;
alter table public.friendships enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Profiles are visible to signed-in users" on public.profiles;
create policy "Profiles are visible to signed-in users" on public.profiles for select to authenticated using (true);
drop policy if exists "Users insert own profile" on public.profiles;
create policy "Users insert own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
drop policy if exists "Users update own profile" on public.profiles;
create policy "Users update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

drop policy if exists "Users see their friendships" on public.friendships;
create policy "Users see their friendships" on public.friendships for select to authenticated using (auth.uid() = requester or auth.uid() = addressee);
drop policy if exists "Users send friend requests" on public.friendships;
create policy "Users send friend requests" on public.friendships for insert to authenticated with check (auth.uid() = requester);
drop policy if exists "Addressee accepts requests" on public.friendships;
create policy "Addressee accepts requests" on public.friendships for update to authenticated using (auth.uid() = addressee) with check (auth.uid() = addressee);

drop policy if exists "Chat participants read messages" on public.messages;
create policy "Chat participants read messages" on public.messages for select to authenticated using (auth.uid() = sender_id or auth.uid() = receiver_id);
drop policy if exists "Sender sends own messages" on public.messages;
create policy "Sender sends own messages" on public.messages for insert to authenticated with check (auth.uid() = sender_id);

-- Realtime untuk chat (abaikan jika tabel sudah masuk publication).
do $$ begin
  alter publication supabase_realtime add table public.messages;
exception when duplicate_object then null;
when undefined_object then null;
end $$;
